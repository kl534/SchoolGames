/**
 * Builds `src/shared/maps/us-states-data.ts` from us-atlas (Albers USA, 975 x 610).
 * Run with `npm run maps`. Nothing from these packages is imported at runtime.
 */
import { execFileSync } from 'node:child_process';
import { readFileSync, writeFileSync } from 'node:fs';
import { feature, neighbors } from 'topojson-client';
import { presimplify, quantile, simplify } from 'topojson-simplify';
import type { GeometryCollection, Topology } from 'topojson-specification';

/** Fraction of the points kept by `simplify` (the most detail that keeps the file under 80 KB). */
const KEEP_QUANTILE = 0.6;
const OUT = 'src/shared/maps/us-states-data.ts';

const kebab = (text: string): string => text.toLowerCase().replace(/[^a-z0-9]+/g, '-');
const round = (n: number): number => Math.round(n * 10) / 10;

interface StateProps {
  name: string;
}
type Ring = number[][];
/** A projected state shape: GeoJSON Polygon or MultiPolygon. */
interface Shape {
  type: 'Polygon' | 'MultiPolygon';
  coordinates: Ring[] | Ring[][];
}
type Named = GeometryCollection<StateProps>['geometries'][number] & {
  properties: StateProps;
};

const atlas = JSON.parse(
  readFileSync('node_modules/us-atlas/states-albers-10m.json', 'utf8'),
) as Topology<{ states: GeometryCollection<StateProps> }>;
const states = atlas.objects.states;
const named = (g: unknown): Named => g as Named;
const NOT_STATES = new Set(['District of Columbia', 'Puerto Rico', 'Guam', 'American Samoa']);
states.geometries = states.geometries.filter(
  (g) => !NOT_STATES.has(named(g).properties.name) && Number(g.id) < 57,
);

const pre = presimplify(atlas);
const simple = simplify(pre, quantile(pre, KEEP_QUANTILE));
const simpleStates = simple.objects.states;
const collection = feature(simple, simpleStates);

const shapes: Record<string, { name: string; d: string; cx: number; cy: number }> = {};
for (const f of collection.features) {
  const geometry = f.geometry as unknown as Shape;
  const polygons = (
    geometry.type === 'Polygon' ? [geometry.coordinates] : geometry.coordinates
  ) as Ring[][];
  const name = (f.properties as unknown as StateProps).name;
  let d = '';
  let largest = { area: -1, cx: 0, cy: 0 };
  for (const polygon of polygons) {
    const outer = polygon[0];
    const xs = outer.map((p) => p[0]);
    const ys = outer.map((p) => p[1]);
    const w = Math.max(...xs) - Math.min(...xs);
    const h = Math.max(...ys) - Math.min(...ys);
    if (w * h > largest.area) {
      largest = {
        area: w * h,
        cx: (Math.max(...xs) + Math.min(...xs)) / 2,
        cy: (Math.max(...ys) + Math.min(...ys)) / 2,
      };
    }
    for (const ring of polygon) {
      d += ring.map((p, i) => `${i === 0 ? 'M' : 'L'}${round(p[0])},${round(p[1])}`).join('') + 'Z';
    }
  }
  shapes[kebab(name)] = { name, d, cx: round(largest.cx), cy: round(largest.cy) };
}

const ids = states.geometries.map((g) => kebab(named(g).properties.name));
const near = neighbors(simpleStates.geometries);
const adjacency: Record<string, string[]> = {};
simpleStates.geometries.forEach((g, i) => {
  adjacency[kebab(named(g).properties.name)] = near[i]
    .map((j) => kebab(named(simpleStates.geometries[j]).properties.name))
    .sort();
});

const sorted = <T>(record: Record<string, T>): Record<string, T> =>
  Object.fromEntries(Object.entries(record).sort(([a], [b]) => (a < b ? -1 : 1)));
if (Object.keys(shapes).length !== 50 || ids.length !== 50) {
  throw new Error(`Expected 50 states, got ${Object.keys(shapes).length}`);
}

const text = `// Generated by \`npm run maps\` from us-atlas (ISC). Do not edit.
export const US_MAP_WIDTH = 975;
export const US_MAP_HEIGHT = 610;
/** By state id (kebab-case of the name, e.g. 'new-york'). */
export const US_STATE_SHAPES: Record<string, { name: string; d: string; cx: number; cy: number }> = ${JSON.stringify(sorted(shapes))};
/** States that share a border (topojson \`neighbors\` on the states object), ids sorted. */
export const US_STATE_NEIGHBORS: Record<string, string[]> = ${JSON.stringify(sorted(adjacency))};
`;
writeFileSync(OUT, text);
execFileSync('npx', ['prettier', '--write', OUT], { stdio: 'inherit' });
console.log(`${OUT}: ${(readFileSync(OUT).length / 1024).toFixed(1)} KB`);
